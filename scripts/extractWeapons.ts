import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";
import { makeBuilder } from "../src/engine/buildWeapon";

const wanted = process.argv.slice(2);
if (wanted.length === 0) {
  console.log('usage: npx tsx scripts/extractWeapons.ts "Uchigatana" "Moonveil"');
  process.exit(1);
}

const file = resolve("..", "reference-calculator", "public", "regulation-vanilla-v1.17.js");
const data = JSON.parse(readFileSync(file, "utf8"));
const build = makeBuilder(data);
const out: any[] = [];

for (const name of wanted) {
  const w = data.weapons.find((x: any) => x.name === name);
  if (!w) {
    console.log(`NOT FOUND: "${name}"`);
    continue;
  }
  const notes: string[] = [];
  out.push(build(w, notes));
  notes.forEach((n) => console.log("note:", n));
  console.log(`ok: ${w.name}`);
}

mkdirSync("src/data", { recursive: true });
writeFileSync(
  "src/data/weapons.ts",
  `// GENERATED by scripts/extractWeapons.ts from regulation-vanilla-v1.17 of\n` +
    `// github.com/ThomasJClark/elden-ring-weapon-calculator (MIT). Do not edit by hand.\n` +
    `import type { Weapon } from "../weapon";\n\n` +
    `export const weapons: Weapon[] = ${JSON.stringify(out)};\n`
);
console.log(`wrote src/data/weapons.ts with ${out.length} weapons`);