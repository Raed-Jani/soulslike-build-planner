import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

// Reads the reference calculator's vanilla data (MIT licensed, credit it in your README)
// and writes just the weapons you ask for, in this project's Weapon shape.

const DAMAGE_TYPES = ["physical", "magic", "fire", "lightning", "holy"] as const;
const DEFAULT_GRAPH_ID = 0;

const wanted = process.argv.slice(2);
if (wanted.length === 0) {
  console.log('usage: npx tsx scripts/extractWeapons.ts "Uchigatana" "Moonveil"');
  process.exit(1);
}

const file = resolve("..", "reference-calculator", "public", "regulation-vanilla-v1.17.js");
const data = JSON.parse(readFileSync(file, "utf8"));

// A curve is stored as a few stages. Turn it into an array: curve[stat] for stat 0..148
// (148 because two-handing can push Strength to 99 * 1.5).
function buildCurve(stages: { maxVal: number; maxGrowVal: number; adjPt: number }[]): number[] {
  const curve: number[] = new Array(149).fill(0);
  for (let i = 1; i < stages.length; i++) {
    const prev = stages[i - 1];
    const stage = stages[i];
    const from = i === 1 ? 1 : prev.maxVal + 1;
    const to = i === stages.length - 1 ? 148 : stage.maxVal;
    for (let stat = from; stat <= to; stat++) {
      let ratio = (stat - prev.maxVal) / (stage.maxVal - prev.maxVal);
      ratio = Math.max(0, Math.min(1, ratio));
      if (prev.adjPt > 0) ratio = ratio ** prev.adjPt;
      else if (prev.adjPt < 0) ratio = 1 - (1 - ratio) ** -prev.adjPt;
      curve[stat] = prev.maxGrowVal + (stage.maxGrowVal - prev.maxGrowVal) * ratio;
    }
  }
  return curve;
}

const curveCache = new Map<number, number[]>();
function getCurve(id: number): number[] {
  if (!curveCache.has(id)) curveCache.set(id, buildCurve(data.calcCorrectGraphs[id]));
  return curveCache.get(id)!;
}

const out: any[] = [];

for (const name of wanted) {
  const matches = data.weapons.filter((w: any) => w.name === name);
  if (matches.length === 0) {
    const similar = data.weapons.filter((w: any) => w.name.includes(name)).slice(0, 10);
    console.log(`NOT FOUND: "${name}". Similar:`, similar.map((w: any) => w.name));
    continue;
  }
  if (matches.length > 1) console.log(`warning: ${matches.length} weapons named "${name}", using the first`);
  const w = matches[0];

  const reinforce = data.reinforceTypes[w.reinforceTypeId]; // one row per upgrade level
  const correct = data.attackElementCorrects[w.attackElementCorrectId];

  // damage at each level = base damage * that level's multiplier
  const attack = reinforce.map((row: any) => {
    const level: Record<string, number> = {};
    for (const [id, base] of w.attack) {
      if (id > 4) continue; // ignore status buildup for now
      level[DAMAGE_TYPES[id]] = base * (row.attack[id] ?? 0);
    }
    return level;
  });

  // scaling at each level = base scaling * that level's multiplier
  const attributeScaling = reinforce.map((row: any) => {
    const level: Record<string, number> = {};
    for (const [stat, base] of w.attributeScaling) {
      level[stat] = base * row.attributeScaling[stat];
    }
    return level;
  });

  // which stats scale which damage type
  const attackElementCorrect: Record<string, string[]> = {};
  DAMAGE_TYPES.forEach((type, id) => {
    const list: string[] = [];
    for (const [stat, value] of Object.entries(correct[id] ?? {})) {
      if (value === true) list.push(stat);
      else console.log(`note: ${name} ${type}/${stat} uses partial scaling (${value}), skipped`);
    }
    if (list.length > 0) attackElementCorrect[type] = list;
  });

  // one curve per damage type (default curve unless the weapon names another)
  const calcCorrectGraphs: Record<string, number[]> = {};
  DAMAGE_TYPES.forEach((type, id) => {
    calcCorrectGraphs[type] = getCurve(w.calcCorrectGraphIds?.[id] ?? DEFAULT_GRAPH_ID);
  });

  out.push({ name: w.name, requirements: w.requirements, attack, attributeScaling, attackElementCorrect, calcCorrectGraphs });
  console.log(`ok: ${w.name} (${reinforce.length} upgrade levels)`);
}

mkdirSync("src/data", { recursive: true });
writeFileSync(
  "src/data/weapons.ts",
  `// GENERATED by scripts/extractWeapons.ts from regulation-vanilla-v1.17 of\n` +
    `// github.com/ThomasJClark/elden-ring-weapon-calculator (MIT). Do not edit by hand.\n` +
    `import type { Weapon } from "../weapon";\n\n` +
    `export const weapons: Weapon[] = ${JSON.stringify(out)};\n`
);
console.log(`wrote src/data/weapons.ts with ${out.length} weapons`);

